-- Formato nuevo: clasificacion de todos contra todos y eliminatorias por nivel (06/10/2026, a
-- pedido del usuario, despues de ver la liga de ejemplo de 16 en grupos).
--
-- 1. CLASIFICACION. Todos los inscritos en un solo grupo. Carreras de 4 en las que cada jugador
--    enfrenta al menos una vez a cada uno de los demas, y todos corren las mismas veces (si no, los
--    puntos no serian comparables). Los calendarios vienen de `torneo_calendarios`, buscados por
--    computadora para 4 a 32 jugadores. Con 16 sale exacto: 20 carreras, 5 por jugador, cada par
--    se cruza una sola vez.
-- 2. ELIMINATORIAS POR NIVEL. Con la tabla de la clasificacion se arman carreras de jugadores del
--    mismo nivel: 1.º-4.º, 5.º-8.º, 9.º-12.º, 13.º-16.º. De cada una pasan los 2 primeros, que se
--    vuelven a juntar por nivel (los que venian de arriba con los de arriba), hasta que queda una
--    sola carrera: la Gran Final. Todos siguen en juego: hasta el nivel mas bajo puede llegar.
--
-- En la base, la clasificacion sigue siendo `tipo = 'grupo'` (un solo grupo, 'A') y las
-- eliminatorias `tipo = 'final'`, con `grupo = '<ronda>-<nivel>'`. Asi no cambian las tablas,
-- `torneo_tabla`, la captura ni la confirmacion.

create table if not exists public.torneo_calendarios (
  jugadores int primary key check (jugadores between 4 and 32),
  -- Lista de carreras; cada una, los indices (0..n-1) de sus 4 jugadores.
  carreras  jsonb not null
);
alter table public.torneo_calendarios enable row level security;
drop policy if exists torneo_calendarios_select on public.torneo_calendarios;
create policy torneo_calendarios_select on public.torneo_calendarios for select to authenticated using (true);

create or replace function public.torneo_nombre_carrera(p_carrera public.torneo_carreras)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when p_carrera.tipo = 'libre' then 'Kart Garage'
    when p_carrera.tipo = 'grupo' then 'Carrera ' || p_carrera.numero || ' · Clasificación'
    else 'Carrera ' || p_carrera.numero || ' · Eliminatorias'
  end;
$$;

-- Una ronda de eliminatorias. `p_jugadores` va en orden de nivel (el mejor primero): se parte en
-- tramos consecutivos de hasta 4, lo mas parejos posible (10 → 4, 3, 3).
create or replace function public.torneo_crear_ronda(p_torneo uuid, p_ronda int, p_jugadores uuid[])
returns int
language plpgsql
security definer
set search_path = public
as $$
declare
  n int := cardinality(p_jugadores);
  k int := ceil(n / 4.0);
  v_base int;
  v_ids uuid[] := '{}';
  v_id uuid;
begin
  select coalesce(max(numero), 0) into v_base from torneo_carreras where torneo_id = p_torneo;
  for j in 1..k loop
    insert into torneo_carreras (torneo_id, tipo, grupo, ronda, numero, cupo, creada_por)
    values (p_torneo, 'final', p_ronda || '-' || j, p_ronda, v_base + j, 4, auth.uid())
    returning id into v_id;
    v_ids := v_ids || v_id;
  end loop;
  for i in 0..n - 1 loop
    insert into torneo_carrera_jugadores (carrera_id, user_id)
    values (v_ids[(i * k) / n + 1], p_jugadores[i + 1]);
  end loop;
  return k;
end;
$$;

create or replace function public.torneo_sortear(p_torneo uuid)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_t torneos;
  v_jug uuid[];
  n int;
  v_cal jsonb;
  v_id uuid;
  v_total int;
begin
  select * into v_t from torneos where id = p_torneo for update;
  if not found then raise exception 'No existe esa liga.'; end if;
  if v_t.fase in ('terminado', 'cancelado') then raise exception 'Esta liga ya terminó.'; end if;

  select array_agg(user_id order by random()) into v_jug from torneo_inscritos where torneo_id = p_torneo;
  n := coalesce(cardinality(v_jug), 0);
  if n < 4 then raise exception 'Se necesitan al menos 4 inscritos para sortear (hay %).', n; end if;
  select carreras into v_cal from torneo_calendarios where jugadores = n;
  if v_cal is null then raise exception 'Una liga admite hasta 32 jugadores (hay %).', n; end if;

  delete from torneo_carreras where torneo_id = p_torneo;
  delete from torneo_grupos where torneo_id = p_torneo;

  insert into torneo_grupos (torneo_id, user_id, grupo) select p_torneo, u, 'A' from unnest(v_jug) u;

  v_total := jsonb_array_length(v_cal);
  for k in 0..v_total - 1 loop
    insert into torneo_carreras (torneo_id, tipo, grupo, ronda, numero, cupo, creada_por)
    values (p_torneo, 'grupo', 'A', k + 1, k + 1, 4, auth.uid())
    returning id into v_id;
    insert into torneo_carrera_jugadores (carrera_id, user_id)
    select v_id, v_jug[(x)::int + 1] from jsonb_array_elements_text(v_cal -> k) x;
  end loop;

  update torneos set fase = 'grupos', campeon = null, sorteo_fallido_at = null where id = p_torneo;

  perform torneo_avisar(v_jug, '🏎️ ¡Ya se sorteó ' || v_t.nombre || '!',
    'Ya está el calendario de clasificación: corres ' || (4 * v_total / n) || ' carreras'
      || coalesce(' (' || nullif(torneo_horario(v_t), '') || ')', '') || '. Revisa Torneos.',
    jsonb_build_object('torneo_id', p_torneo));

  return jsonb_build_object('carreras', v_total, 'jugadores', n, 'por_jugador', 4 * v_total / n);
end;
$$;

create or replace function public.torneo_avanzar(p_torneo uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_t torneos;
  v_ronda int;
  v_carreras int;
  v_pasan uuid[];
  v_todos uuid[];
  v_campeon uuid;
  v_apodo text;
begin
  select * into v_t from torneos where id = p_torneo for update;
  if v_t.fase not in ('grupos', 'finales') then return; end if;
  select array_agg(user_id) into v_todos from torneo_grupos where torneo_id = p_torneo;

  if v_t.fase = 'grupos' then
    if exists (select 1 from torneo_carreras
                where torneo_id = p_torneo and tipo = 'grupo' and estado <> 'completada') then
      return;
    end if;
    -- Todos siguen, en el orden de la clasificacion.
    select array_agg(user_id order by puntos desc, victorias desc, posicion_media, user_id)
      into v_pasan
      from torneo_tabla where torneo_id = p_torneo and tipo = 'grupo';

    -- Con 4 o menos, la clasificacion ya fue la final.
    if cardinality(v_pasan) <= 4 then
      v_campeon := v_pasan[1];
      update torneos set fase = 'terminado', campeon = v_campeon where id = p_torneo;
      select apodo into v_apodo from torneo_jugadores where user_id = v_campeon;
      perform torneo_avisar(v_todos, '🏆 ¡Tenemos campeón!',
        coalesce(v_apodo, 'Alguien') || ' ganó ' || v_t.nombre || '.', jsonb_build_object('torneo_id', p_torneo));
      return;
    end if;
    v_ronda := 1;
  else
    select max(ronda) into v_ronda from torneo_carreras where torneo_id = p_torneo and tipo = 'final';
    if exists (select 1 from torneo_carreras
                where torneo_id = p_torneo and tipo = 'final' and ronda = v_ronda
                  and estado <> 'completada') then
      return;
    end if;
    select count(*) into v_carreras
      from torneo_carreras where torneo_id = p_torneo and tipo = 'final' and ronda = v_ronda;

    if v_carreras = 1 then
      select cj.user_id into v_campeon
        from torneo_carreras c join torneo_carrera_jugadores cj on cj.carrera_id = c.id
       where c.torneo_id = p_torneo and c.tipo = 'final' and c.ronda = v_ronda and cj.posicion = 1;
      update torneos set fase = 'terminado', campeon = v_campeon where id = p_torneo;
      select apodo into v_apodo from torneo_jugadores where user_id = v_campeon;
      perform torneo_avisar(v_todos, '🏆 ¡Tenemos campeón!',
        coalesce(v_apodo, 'Alguien') || ' ganó la Gran Final de ' || v_t.nombre || '.',
        jsonb_build_object('torneo_id', p_torneo));
      return;
    end if;

    -- Los 2 primeros de cada carrera, conservando el nivel: primero los de la carrera de arriba.
    select array_agg(user_id order by nivel, lugar)
      into v_pasan
      from (select t.user_id, split_part(t.grupo, '-', 2)::int as nivel,
                   row_number() over (partition by t.grupo
                     order by t.puntos desc, t.victorias desc, t.posicion_media, t.user_id) as lugar
              from torneo_tabla t
             where t.torneo_id = p_torneo and t.tipo = 'final' and t.ronda = v_ronda) r
     where lugar <= 2;
    v_ronda := v_ronda + 1;
  end if;

  update torneos set fase = 'finales' where id = p_torneo;
  v_carreras := torneo_crear_ronda(p_torneo, v_ronda, v_pasan);
  if v_ronda = 1 then
    perform torneo_avisar(v_pasan, '🏁 ¡Empiezan las eliminatorias!',
      case when v_carreras = 1 then 'Terminó la clasificación: corres la Gran Final de ' || v_t.nombre || '.'
           else 'Terminó la clasificación de ' || v_t.nombre || '. Ya está tu carrera por nivel: pasan los 2 primeros.' end,
      jsonb_build_object('torneo_id', p_torneo));
  else
    perform torneo_avisar(v_pasan,
      case when v_carreras = 1 then '🏁 ¡Estás en la Gran Final!' else '🏁 ¡Pasaste de ronda!' end,
      case when v_carreras = 1 then 'Corres la Gran Final de ' || v_t.nombre || '. Revisa el horario en Torneos.'
           else 'Pasaste a la ronda ' || v_ronda || ' de eliminatorias de ' || v_t.nombre || '.' end,
      jsonb_build_object('torneo_id', p_torneo));
  end if;
end;
$$;

